import type { Monaco } from "@monaco-editor/react";

let configured = false;

export function configureDeepTraceMonaco(monaco: Monaco): void {
  if (configured) {
    return;
  }
  configured = true;

  // Register Dalvik Smali language
  monaco.languages.register({ id: "smali" });
  monaco.languages.setMonarchTokensProvider("smali", {
    defaultToken: "",
    tokenPostfix: ".smali",
    keywords: [
      ".class",
      ".super",
      ".source",
      ".field",
      ".method",
      ".end",
      ".registers",
      ".locals",
      ".param",
      ".line",
      ".prologue",
      ".annotation",
      ".subannotation",
      "public",
      "private",
      "protected",
      "static",
      "final",
      "native",
      "synthetic",
      "bridge",
      "constructor",
    ],
    opcodes: [
      "invoke-virtual",
      "invoke-super",
      "invoke-direct",
      "invoke-static",
      "invoke-interface",
      "invoke-virtual/range",
      "invoke-static/range",
      "move-result",
      "move-result-wide",
      "move-result-object",
      "move-exception",
      "move-object",
      "const",
      "const/4",
      "const/16",
      "const-string",
      "const-class",
      "iget-object",
      "iput-object",
      "sget-object",
      "sput-object",
      "new-instance",
      "new-array",
      "array-length",
      "check-cast",
      "if-eq",
      "if-ne",
      "if-eqz",
      "if-nez",
      "if-ltz",
      "if-gez",
      "goto",
      "return-void",
      "return",
      "return-object",
      "throw",
      "nop",
    ],
    tokenizer: {
      root: [
        [/#.*$/, "comment"],
        [/"([^"\\]|\\.)*"/, "string"],
        [
          /\.[a-zA-Z_-]+/,
          {
            cases: {
              "@keywords": "keyword.directive",
              "@default": "keyword",
            },
          },
        ],
        [/\b[vp][0-9]+\b/, "variable.register"],
        [/L[a-zA-Z0-9_/$]+;/, "type.identifier"],
        [/\[+[ZBSCIFJD]/, "type.identifier"],
        [
          /\b(public|private|protected|static|final|native|constructor|synthetic)\b/,
          "keyword",
        ],
        [
          /[a-z][a-z0-9-/]*/,
          {
            cases: {
              "@opcodes": "keyword.opcode",
              "@default": "identifier",
            },
          },
        ],
        [/:\w+/, "tag.label"],
        [/->/, "operator"],
        [/-?0x[0-9a-fA-F]+/, "number.hex"],
        [/-?\d+/, "number"],
      ],
    },
  });

  // Register ARM64 (AArch64) Assembly language
  monaco.languages.register({ id: "arm64" });
  monaco.languages.setMonarchTokensProvider("arm64", {
    ignoreCase: true,
    defaultToken: "",
    tokenPostfix: ".arm64",
    instructions: [
      "STP",
      "LDP",
      "STR",
      "STRB",
      "STRH",
      "LDR",
      "LDRB",
      "LDRH",
      "LDRSW",
      "MOV",
      "MOVZ",
      "MOVK",
      "MOVN",
      "ADRP",
      "ADR",
      "ADD",
      "SUB",
      "SUBS",
      "ADDS",
      "MUL",
      "UDIV",
      "AND",
      "ORR",
      "EOR",
      "LSL",
      "LSR",
      "ASR",
      "CMP",
      "CMN",
      "TST",
      "B",
      "BL",
      "BLR",
      "BR",
      "RET",
      "CBZ",
      "CBNZ",
      "TBZ",
      "TBNZ",
      "B.EQ",
      "B.NE",
      "B.LT",
      "B.LE",
      "B.GT",
      "B.GE",
      "B.HI",
      "B.LS",
      "CSEL",
      "NOP",
    ],
    tokenizer: {
      root: [
        [/;.*$/, "comment"],
        [/\/\/.*$/, "comment"],
        [/"([^"\\]|\\.)*"/, "string"],
        [/^[0-9a-fA-F]{4,16}:/, "number.address"],
        [/^\.[a-zA-Z0-9_]+:/, "tag.label"],
        [/\b(sub_[0-9a-fA-F]+|loc_[0-9a-fA-F]+|j_[a-zA-Z0-9_]+)\b/, "entity.name.function"],
        [
          /\b([XW]([0-9]|[12][0-9]|30)|SP|FP|LR|XZR|WZR|PC|[QDVHSB]([0-9]|[12][0-9]|3[01]))\b/i,
          "variable.register",
        ],
        [
          /\b[A-Z][A-Z0-9.]*\b/,
          {
            cases: {
              "@instructions": "keyword.opcode",
              "@default": "identifier",
            },
          },
        ],
        [/#-?0x[0-9a-fA-F]+/, "number.hex"],
        [/0x[0-9a-fA-F]+/, "number.hex"],
        [/#-?\d+/, "number"],
        [/[\[\]!{},]/, "delimiter"],
      ],
    },
  });

  // Calm Aetox-style dark editor theme matching #0f0f11 card ground
  monaco.editor.defineTheme("deeptrace-dark", {
    base: "vs-dark",
    inherit: true,
    rules: [
      { token: "comment", foreground: "56585f", fontStyle: "italic" },
      { token: "keyword.directive", foreground: "b79bf5" },
      { token: "keyword.opcode", foreground: "35d0e0" },
      { token: "keyword", foreground: "7fa8ff" },
      { token: "variable.register", foreground: "d29922" },
      { token: "type.identifier", foreground: "7fb0ff" },
      { token: "entity.name.function", foreground: "58a6ff" },
      { token: "tag.label", foreground: "e0939e" },
      { token: "number.address", foreground: "7d8087" },
      { token: "number.hex", foreground: "d29922" },
      { token: "number", foreground: "d29922" },
      { token: "string", foreground: "9ff0ad" },
    ],
    colors: {
      "editor.background": "#0f0f11",
      "editor.foreground": "#f2f2f3",
      "editor.lineHighlightBackground": "#16161a",
      "editor.selectionBackground": "#2f6bff33",
      "editorLineNumber.foreground": "#56585f",
      "editorLineNumber.activeForeground": "#b0b3b8",
      "editorGutter.background": "#0f0f11",
      "diffEditor.insertedTextBackground": "#3fb95022",
      "diffEditor.removedTextBackground": "#f8514922",
      "diffEditor.insertedLineBackground": "#3fb95014",
      "diffEditor.removedLineBackground": "#f8514914",
    },
  });
}
